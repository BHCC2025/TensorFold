"""Generates zig/kernels/xpu/ggml_tables.h and ggml_tables_iq1s.h (OpenCL __constant lookup tables) from llama.cpp's
ggml-common.h, verbatim values. The iq1s grid is its own header so each file stays under 600 lines; ggml_tables.h includes it.
usage: python3 tools/gen_ggml_tables.py [LLAMA_CPP_DIR]   (run from the repository root)"""
import os
import re
import sys

root = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/llm/llama.cpp")
src = open(os.path.join(root, "ggml/src/ggml-common.h")).read()
# the C branch of the iq1s grid (uint64) is the second definition; the GPU variant (uint32) is a different table
main = [("kmask_iq2xs", "uchar"), ("ksigns_iq2xs", "uchar"), ("ksigns64", "ulong"), ("iq2xxs_grid", "ulong"), ("iq2xs_grid", "ulong"),
        ("iq2s_grid", "ulong"), ("iq3xxs_grid", "uint"), ("iq3s_grid", "uint"), ("kvalues_iq4nl", "char")]
iq1s = [("iq1s_grid", "ulong")]
head = "// Generated by tools/gen_ggml_tables.py from llama.cpp ggml/src/ggml-common.h - do not edit.\n"


def tables(want):
    out = []
    for name, ty in want:
        m = re.search(r"GGML_TABLE_BEGIN\((\w+), " + name + r", (\w+)\)(.*?)GGML_TABLE_END\(\)", src, re.S)
        nums = re.findall(r"-?0x[0-9a-fA-F]+|-?\d+", m.group(3))
        n = 2048 if m.group(2) == "NGRID_IQ1S" else int(m.group(2))
        assert len(nums) == n, (name, len(nums), n)
        suffix = "UL" if ty == "ulong" else ("u" if ty == "uint" else "")
        out.append(f"__constant {ty} {name}[{n}] = {{\n")
        for i in range(0, n, 8):
            out.append("    " + ", ".join(v + suffix for v in nums[i:i + 8]) + ",\n")
        out.append("};\n")
    return out


d = "zig/kernels/xpu"
open(f"{d}/ggml_tables.h", "w").write("".join([head] + tables(main) + ['#include "ggml_tables_iq1s.h"\n']))
open(f"{d}/ggml_tables_iq1s.h", "w").write("".join([head] + tables(iq1s)))
print("ok")
